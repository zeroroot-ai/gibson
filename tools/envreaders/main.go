// Command envreaders writes and checks configs/env-readers.txt, the set of
// environment variable names the gibson source can read.
//
// It is the producer half of ADR-0094 layer 2 (charts#303). The chart injects
// env vars into containers whose source lives here, and its merge gate fails
// when it injects a name that is absent from this set. The chart vendors the
// file, so the set must come from the repository that owns the readers.
//
// The set holds the real env reads only (gibson#1128). An all-caps string
// or selector is not a read: time.RFC1123Z entered the old set when
// gibson#1125 used it in a Date header, and an error code entered it the
// same way. Such a name hides a dead env var from the charts gate.
//
// The scan parses every tracked Go file that is not a test, and reads them
// together (reads.go). A name counts when it reaches one of these reads:
//
//   - os.Getenv, os.LookupEnv or syscall.Getenv, with a string literal, a
//     constant of any package, a struct field set from a literal or a
//     constant, or a loop variable over a list of these;
//   - a function of the same package, or of an imported package, that
//     passes one of its string parameters to a read: durationOr and intOr
//     in cmd/ext-authz;
//   - a parameter of type func(string) string, the getenv that
//     operators/connector passes in, or a closure that reads env with its
//     parameter;
//   - an `env:"NAME"` struct tag.
//
// A set that MISSES a name makes the chart gate report a live env var as
// dead, and deleting one of those boots a pod with an empty value. So a new
// read form needs a new rule here, and a test in main_test.go.
//
// A name in a comment is not a reader. A name in a test file is not a reader.
//
// Usage:
//
//	envreaders -dir <repo root> -write   refresh configs/env-readers.txt
//	envreaders -dir <repo root> -check   exit 1 when the file is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// Artifact is the committed reader set, relative to the repository root.
const Artifact = "configs/env-readers.txt"

// MinFiles and MinNames refuse a scan that read almost nothing. A wrong
// working directory or an empty checkout must not write an empty set.
const (
	MinFiles = 200
	MinNames = 100
)

const header = `# env-readers.txt — GENERATED by tools/envreaders. Do not hand-edit.
# Refresh with ` + "`make env-readers`" + `. ` + "`make check-env-readers`" + ` fails when it is stale.
#
# Every environment variable name the gibson source reads (ADR-0094 layer 2,
# charts#303): each name that reaches os.Getenv, os.LookupEnv, a reader
# helper, a getenv parameter or an env struct tag, from every tracked Go file
# that is not a test (gibson#1128). zeroroot-ai/charts vendors this file.
`

// NamesInSource returns the env names one Go source file can read. A read
// through a helper or a constant of another file needs Scan, which reads
// the files together.
func NamesInSource(filename string, src []byte) map[string]bool {
	return envReads(map[string][]byte{filename: src})
}

// trackedGoFiles lists the Go files git tracks under dir that are not tests,
// vendored code or test data. Tracked files only: CI checks sibling
// repositories out inside the tree, and those are not this repository.
func trackedGoFiles(dir string) ([]string, error) {
	// The one variable is the repository root the caller named.
	cmd := exec.Command("git", "-C", dir, "ls-files", "-z", "--", "*.go") //nolint:gosec // G204: fixed argv, dir is the scan root
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	raw, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files in %s: %w: %s", dir, err, strings.TrimSpace(stderr.String()))
	}
	var files []string
	for _, f := range strings.Split(string(raw), "\x00") {
		if f == "" || strings.HasSuffix(f, "_test.go") {
			continue
		}
		skip := false
		for _, part := range strings.Split(filepath.ToSlash(filepath.Dir(f)), "/") {
			if part == "testdata" || part == "vendor" {
				skip = true
			}
		}
		if !skip {
			files = append(files, f)
		}
	}
	return files, nil
}

// Scan returns the sorted reader set of the repository at dir.
func Scan(dir string, minFiles, minNames int) ([]string, error) {
	files, err := trackedGoFiles(dir)
	if err != nil {
		return nil, err
	}
	if len(files) < minFiles {
		return nil, fmt.Errorf("scanned %d Go file(s) in %s, the floor is %d: this is not the gibson tree", len(files), dir, minFiles)
	}
	srcs := make(map[string][]byte, len(files))
	for _, f := range files {
		src, err := os.ReadFile(filepath.Join(dir, f)) //nolint:gosec // G304: f is a path git tracks under the scan root
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", f, err)
		}
		srcs[f] = src
	}
	set := envReads(srcs)
	if len(set) < minNames {
		return nil, fmt.Errorf("found %d name(s) in %d file(s), the floor is %d: the scan read nothing", len(set), len(files), minNames)
	}
	names := make([]string, 0, len(set))
	for n := range set {
		names = append(names, n)
	}
	sort.Strings(names)
	return names, nil
}

// Render is the artifact text for a reader set.
func Render(names []string) string {
	return header + strings.Join(names, "\n") + "\n"
}

// Parse reads the names out of artifact text.
func Parse(text string) []string {
	var names []string
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		names = append(names, line)
	}
	return names
}

// Drift compares the committed set with the scanned set.
func Drift(committed, scanned []string) (missing, stale []string) {
	have := map[string]bool{}
	for _, n := range committed {
		have[n] = true
	}
	want := map[string]bool{}
	for _, n := range scanned {
		want[n] = true
		if !have[n] {
			missing = append(missing, n)
		}
	}
	for _, n := range committed {
		if !want[n] {
			stale = append(stale, n)
		}
	}
	return missing, stale
}

// say prints one message. A failed write to stdout or stderr has no reader
// to report it to, so the error is dropped.
func say(w io.Writer, format string, args ...any) {
	_, _ = fmt.Fprintf(w, format, args...)
}

func run(args []string, stdout, stderr io.Writer) int {
	return runWithFloors(args, stdout, stderr, MinFiles, MinNames)
}

// runWithFloors is run with the two floors as arguments, so a test can run
// the whole command on a small tree.
func runWithFloors(args []string, stdout, stderr io.Writer, minFiles, minNames int) int {
	fs := flag.NewFlagSet("envreaders", flag.ContinueOnError)
	fs.SetOutput(stderr)
	dir := fs.String("dir", ".", "repository root")
	write := fs.Bool("write", false, "refresh "+Artifact)
	check := fs.Bool("check", false, "exit 1 when "+Artifact+" is stale")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *write == *check {
		say(stderr, "envreaders: give exactly one of -write and -check\n")
		return 2
	}
	names, err := Scan(*dir, minFiles, minNames)
	if err != nil {
		say(stderr, "envreaders: %v\n", err)
		return 2
	}
	path := filepath.Join(*dir, Artifact)
	if *write {
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			say(stderr, "envreaders: %v\n", err)
			return 2
		}
		if err := os.WriteFile(path, []byte(Render(names)), 0o600); err != nil {
			say(stderr, "envreaders: %v\n", err)
			return 2
		}
		say(stdout, "wrote %s (%d names)\n", Artifact, len(names))
		return 0
	}
	raw, err := os.ReadFile(path) //nolint:gosec // G304: the artifact path under the scan root
	if err != nil {
		say(stderr, "envreaders: %s is missing. Run `make env-readers`.\n", Artifact)
		return 1
	}
	missing, stale := Drift(Parse(string(raw)), names)
	if len(missing) == 0 && len(stale) == 0 && string(raw) == Render(names) {
		say(stdout, "ok  %s matches the source (%d names)\n", Artifact, len(names))
		return 0
	}
	for _, n := range missing {
		say(stderr, "envreaders: the source reads %s and %s does not list it\n", n, Artifact)
	}
	for _, n := range stale {
		say(stderr, "envreaders: %s lists %s and the source no longer reads it\n", Artifact, n)
	}
	say(stderr, "envreaders: %s is stale. Run `make env-readers` and commit the result.\n", Artifact)
	return 1
}

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }
