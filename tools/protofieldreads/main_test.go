package main

import (
	"os"
	"path/filepath"
	"testing"
)

// TestCollectCountsReadsNotWrites builds a throwaway module shaped like a
// generated proto package plus one hand-written consumer, and asserts that
// only reads come back: a getter call and a selector read count, a
// composite-literal key, an assignment and a test file do not.
func TestCollectCountsReadsNotWrites(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/fixture\n\ngo 1.22\n")
	write("api/v1/msg.pb.go", `// Code generated by protoc-gen-go. DO NOT EDIT.
package v1

type AckResponse struct {
	Acked   bool
	Ignored string
	Written int
}

func (x *AckResponse) GetAcked() bool    { return x.Acked }
func (x *AckResponse) GetIgnored() string { return x.Ignored }
func (x *AckResponse) GetWritten() int    { return x.Written }

type Other struct{ Acked bool }

func (x *Other) GetAcked() bool { return x.Acked }
`)
	write("consumer/consumer.go", `package consumer

import v1 "example.com/fixture/api/v1"

func Use(r *v1.AckResponse, o *v1.Other) int {
	_ = r.GetAcked()          // getter: read
	r.Ignored = "set"         // assignment: write
	_ = &v1.AckResponse{Written: 1} // literal key: write
	if o.Acked {              // selector on a different type: read of Other.Acked
		return r.Written      // selector: read
	}
	return 0
}
`)
	write("consumer/consumer_test.go", `package consumer

import v1 "example.com/fixture/api/v1"

func testOnly(r *v1.AckResponse) string { return r.GetIgnored() }
`)

	got, err := collect(dir, "example.com/fixture/api/", "")
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"example.com/fixture/api/v1.AckResponse.Acked",
		"example.com/fixture/api/v1.AckResponse.Written",
		"example.com/fixture/api/v1.Other.Acked",
	}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("got %v, want %v", got, want)
		}
	}
}
