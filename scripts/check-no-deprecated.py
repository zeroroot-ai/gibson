#!/usr/bin/env python3
"""Fail on a `// Deprecated:` marker in hand-written Go code.

ADR-0131 forbids a deprecated symbol that still ships: an old path that stays
next to its replacement is a parallel code path. The fix is to delete the
symbol and move its callers, never to keep both (gibson#691).

SCOPE

  1. Files that git tracks, with the extension `.go`.
  2. Generated files are not scanned. A file is generated when its first
     comment block holds the Go convention `Code generated ... DO NOT EDIT.`,
     or when its name ends in `.pb.go`, `.pb.gw.go`, `.pb.validate.go` or
     `.connect.go`, or starts with `zz_generated`. A generated file repeats the
     markers of its source proto, and the proto drift gate owns those.
  3. The marker is the Go convention: a comment line whose text starts with
     `Deprecated:`. A marker inside a string literal is not a comment and is
     not a finding.

USAGE

  scripts/check-no-deprecated.py            scan the tracked tree
  scripts/check-no-deprecated.py --selftest run the fixtures and exit

Exit 0 on no finding, 1 on a finding, 2 on a usage error.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile

GUARD = "check-no-deprecated"

MARKER_RE = re.compile(r"^\s*//\s*Deprecated:")
GENERATED_RE = re.compile(r"^// Code generated .* DO NOT EDIT\.$")
GENERATED_SUFFIXES = (".pb.go", ".pb.gw.go", ".pb.validate.go", ".connect.go")
GENERATED_PREFIX = "zz_generated"
HEADER_LINES = 40


def is_generated(path: str, lines: list[str]) -> bool:
    name = os.path.basename(path)
    if name.endswith(GENERATED_SUFFIXES) or name.startswith(GENERATED_PREFIX):
        return True
    for line in lines[:HEADER_LINES]:
        if GENERATED_RE.match(line.rstrip("\n")):
            return True
    return False


def findings_in(path: str, lines: list[str]) -> list[tuple[str, int, str]]:
    """Each marker in one file as (path, line number, line text)."""
    if is_generated(path, lines):
        return []
    out = []
    for n, line in enumerate(lines, start=1):
        if MARKER_RE.match(line):
            out.append((path, n, line.rstrip("\n")))
    return out


def tracked_go_files() -> list[str]:
    res = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.go"],
        check=True,
        capture_output=True,
    )
    return [p for p in res.stdout.decode().split("\0") if p]


def scan(paths: list[str]) -> list[tuple[str, int, str]]:
    out = []
    for path in paths:
        if os.path.islink(path) or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as fh:
            lines = fh.readlines()
        out.extend(findings_in(path, lines))
    return out


def selftest() -> int:
    """One fixture per rule. Each red case names its line."""
    cases = [
        (
            "a marker in a hand-written file fails",
            "a.go",
            "package a\n\n// Load returns the catalogue.\n//\n// Deprecated: use NewLoader.\nfunc Load() {}\n",
            [5],
        ),
        (
            "a marker on a field fails",
            "b.go",
            "package b\n\ntype T struct {\n\t// Deprecated: kept for compatibility.\n\tOld string\n}\n",
            [4],
        ),
        (
            "a file with no marker passes",
            "c.go",
            "package c\n\n// Load returns the catalogue.\nfunc Load() {}\n",
            [],
        ),
        (
            "a generated file by header passes",
            "d.go",
            "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage d\n\n// Deprecated: Use X instead.\ntype Y struct{}\n",
            [],
        ),
        (
            "a generated file by name passes",
            "e.pb.go",
            "package e\n\n// Deprecated: Use X instead.\ntype Y struct{}\n",
            [],
        ),
        (
            "the word in a string literal passes",
            "f.go",
            'package f\n\nvar s = "// Deprecated: not a comment"\n',
            [],
        ),
        (
            "the word in prose without the colon passes",
            "g.go",
            "package g\n\n// The deprecated models are filtered out of the list.\nfunc F() {}\n",
            [],
        ),
    ]
    fails = 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, fname, body, want in cases:
            path = os.path.join(tmp, fname)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(body)
            got = [n for _, n, _ in scan([path])]
            if got != want:
                fails += 1
                print(f"{GUARD}: selftest FAIL: {name}: want lines {want}, got {got}")
    if fails:
        return 1
    print(f"{GUARD}: selftest OK ({len(cases)} cases)")
    return 0


def main() -> int:
    findings = scan(tracked_go_files())
    if not findings:
        print(f"{GUARD}: OK. No Deprecated marker in hand-written Go code.")
        return 0
    for path, n, text in findings:
        print(f"{path}:{n}: {text.strip()}")
    print(
        f"{GUARD}: {len(findings)} Deprecated marker(s) in hand-written Go code. "
        "Delete the symbol and move its callers to the replacement (ADR-0131, gibson#691)."
    )
    return 1


if __name__ == "__main__":
    args = sys.argv[1:]
    if args == ["--selftest"]:
        sys.exit(selftest())
    if args:
        print(__doc__)
        sys.exit(2)
    sys.exit(main())
